#!/usr/bin/env node
/**
 * Extracts ``<main class="ez-content">`` (and optional modal overlay) from V17–V31 artboards
 * into TS modules consumed by VendorDesignDiffFixtureView.
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const canvasDir = path.join(scriptDir, "../../design/canvas/project");
const outFile = path.join(scriptDir, "../../features/vendor/design/vendorDesignFixtureHtml.ts");

const SCREENS = [
  { id: "v17", file: "V17-RequestDetail.dc.html", mode: "content" },
  { id: "v18", file: "V18-AdjustAccept.dc.html", mode: "modal" },
  { id: "v19", file: "V19-SendQuote.dc.html", mode: "modal" },
  { id: "v20", file: "V20-Chat.dc.html", mode: "content" },
  { id: "v21", file: "V21-Complete.dc.html", mode: "content" },
  { id: "v22", file: "V22-CancellationOutcome.dc.html", mode: "content" },
  { id: "v23", file: "V23-PaymentRecord.dc.html", mode: "content" },
  { id: "v24", file: "V24-PayoutStatement.dc.html", mode: "content" },
  { id: "v25", file: "V25-Payouts.dc.html", mode: "content" },
  { id: "v26", file: "V26-Disputes.dc.html", mode: "content" },
  { id: "v27", file: "V27-Reviews.dc.html", mode: "content" },
  { id: "v28", file: "V28-ProfileEditor.dc.html", mode: "content" },
  { id: "v29", file: "V29-Notifications.dc.html", mode: "content" },
  { id: "v30", file: "V30-Help.dc.html", mode: "content" },
  { id: "v31", file: "V31-Settings.dc.html", mode: "content" },
];

function extractContent(source) {
  const mainMatch = source.match(/<main class="ez-content">([\s\S]*?)<\/main>/);
  if (!mainMatch) throw new Error("missing ez-content");
  let html = mainMatch[1];
  html = html.replace(/<div class="ez-callout"[\s\S]*$/m, "");
  return html.trim();
}

function extractModalOverlay(source) {
  const content = extractContent(source);
  const scrimMatch = source.match(/(<div class="ez-scrim"[\s\S]*?<\/div><\/div>)/);
  const scrim = scrimMatch?.[1] ?? "";
  return { content, scrim };
}

function escapeTemplateLiteral(value) {
  return value.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

async function main() {
  const entries = [];
  for (const screen of SCREENS) {
    const source = await fs.readFile(path.join(canvasDir, screen.file), "utf8");
    const { content, scrim } =
      screen.mode === "modal" ? extractModalOverlay(source) : { content: extractContent(source), scrim: "" };
    entries.push({ id: screen.id, content, scrim });
  }

  const body = entries
    .map(
      (entry) =>
        `  "${entry.id}": {\n    content: \`${escapeTemplateLiteral(entry.content)}\`,\n    scrim: \`${escapeTemplateLiteral(entry.scrim)}\`,\n  }`,
    )
    .join(",\n");

  const file = `/** Generated by web/scripts/design-diff/extract-vendor-fixtures.mjs — do not edit by hand. */

export type VendorDesignFixtureHtml = {
  content: string;
  scrim: string;
};

export const VENDOR_DESIGN_FIXTURE_HTML: Record<string, VendorDesignFixtureHtml> = {
${body}
};

export const VENDOR_DESIGN_FIXTURE_IDS = ${JSON.stringify(entries.map((entry) => entry.id))} as const;

export type VendorDesignFixtureId = (typeof VENDOR_DESIGN_FIXTURE_IDS)[number];
`;

  await fs.writeFile(outFile, file);
  console.log(`Wrote ${outFile} (${entries.length} fixtures)`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
