#!/usr/bin/env bash
# Per-boot runtime reconciliation for the Eventtz Cloud Agent environment.
#
# Responsibilities (idempotent, must terminate):
#   1. Start the Docker daemon (fuse-overlayfs + legacy iptables for nested VMs).
#   2. Provision the backend's Supabase target:
#        - If SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY are supplied as secrets,
#          use that hosted project.
#        - Otherwise start a self-contained local Supabase stack, apply the
#          backend/sql schema (first boot only) and grant API-role privileges.
#   3. Write backend/.env so the API and the dev terminals can boot.
#
# The dev servers (FastAPI :8000, Next.js :3000) are launched in the background at
# the end (idempotent — skipped if the port is already serving).
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export PATH="$HOME/.local/bin:$PATH"
export DOCKER_HOST="unix:///var/run/docker.sock"

# --- 1. Docker daemon -------------------------------------------------------
if ! docker info >/dev/null 2>&1; then
  echo "==> Starting Docker daemon"
  sudo update-alternatives --set iptables /usr/sbin/iptables-legacy >/dev/null 2>&1 || true
  sudo update-alternatives --set ip6tables /usr/sbin/ip6tables-legacy >/dev/null 2>&1 || true
  sudo bash -c 'nohup dockerd --storage-driver=fuse-overlayfs --firewall-backend=iptables \
    --host=unix:///var/run/docker.sock >/tmp/dockerd.log 2>&1 &'
  for _ in $(seq 1 30); do
    if sudo test -S /var/run/docker.sock; then break; fi
    sleep 1
  done
fi
sudo chmod 666 /var/run/docker.sock 2>/dev/null || true
for _ in $(seq 1 30); do
  if docker info >/dev/null 2>&1; then break; fi
  sleep 1
done
docker info >/dev/null 2>&1 || { echo "ERROR: Docker daemon did not come up"; cat /tmp/dockerd.log; exit 1; }
echo "==> Docker is up"

# --- 2. Supabase target -----------------------------------------------------
if [ -n "${SUPABASE_URL:-}" ] && [ -n "${SUPABASE_SERVICE_ROLE_KEY:-}" ]; then
  echo "==> Using provided (hosted) Supabase project from secrets"
  SB_URL="$SUPABASE_URL"
  SB_KEY="$SUPABASE_SERVICE_ROLE_KEY"
else
  echo "==> Starting local Supabase stack"
  cd "$REPO_ROOT"
  supabase start >/dev/null 2>&1 || supabase start
  eval "$(supabase status -o env)"
  SB_URL="$API_URL"
  SB_KEY="$SERVICE_ROLE_KEY"

  DB_CONTAINER="$(docker ps --filter 'name=supabase_db' --format '{{.Names}}' | head -1)"
  SCHEMA_READY="$(docker exec -i "$DB_CONTAINER" psql -U postgres -d postgres -tAc "select to_regclass('public.users');" 2>/dev/null || true)"
  if [ "$SCHEMA_READY" != "users" ]; then
    echo "==> Applying backend/sql migrations to local database (first boot)"
    for f in $(ls "$REPO_ROOT"/backend/sql/*.sql | sort); do
      docker exec -i "$DB_CONTAINER" psql -U postgres -d postgres -v ON_ERROR_STOP=1 -q < "$f"
    done
    docker exec -i "$DB_CONTAINER" psql -U postgres -d postgres -v ON_ERROR_STOP=1 -q < "$REPO_ROOT/.cursor/supabase-grants.sql"
    echo "==> Schema applied"
  else
    echo "==> Local database schema already present; skipping migrations"
  fi
fi

# --- 3. backend/.env --------------------------------------------------------
cat > "$REPO_ROOT/backend/.env" <<ENV
# Auto-generated by .cursor/start.sh — do not commit.
CORS_ALLOWED_ORIGINS=http://localhost:3000,http://127.0.0.1:3000,http://[::1]:3000
FRONTEND_URL=http://localhost:3000
SUPABASE_URL=${SB_URL}
SUPABASE_SERVICE_ROLE_KEY=${SB_KEY}
LOG_LEVEL=INFO
IS_PRODUCTION=false
SENTRY_DSN=
ENV

echo "==> Supabase ready (URL: ${SB_URL})"

# --- 4. Dev servers (background, idempotent) --------------------------------
serving() { curl -fsS -o /dev/null -m 2 "http://127.0.0.1:$1$2" 2>/dev/null; }

if serving 8000 /health; then
  echo "==> Backend already serving on :8000"
else
  echo "==> Launching backend (uvicorn :8000)"
  nohup bash "$REPO_ROOT/.cursor/run-backend.sh" >/tmp/eventtz-backend.log 2>&1 &
fi

if serving 3000 /; then
  echo "==> Frontend already serving on :3000"
else
  echo "==> Launching frontend (next dev :3000)"
  nohup bash "$REPO_ROOT/.cursor/run-frontend.sh" >/tmp/eventtz-frontend.log 2>&1 &
fi

echo "==> start.sh complete (backend :8000, frontend :3000, logs in /tmp/eventtz-*.log)"
